'use client'

/*
 * BikeFormGallery — Gallery & Media section of the BikeForm.
 *
 * MPD Task A-08.6:
 *   "Gallery: Hero Image URL (required, HTTPS), Thumbnail / Blur Placeholder
 *   URL (optional), Gallery Images with URL + Alt Text (dynamic list, max 15,
 *   drag-and-drop reorder, add/remove, live preview), 360° Video URL (optional).
 *   HTTPS URL validation, duplicate URL prevention, blur validation,
 *   parent error merging."
 *
 * FIELDS:
 *
 *   Hero Image (required):
 *     heroImageUrl        — primary motorcycle photo (HTTPS, required)
 *     heroBlurDataUrl     — low-quality blur placeholder (HTTPS, optional)
 *                           Labeled "Thumbnail / Blur Placeholder" in the UI.
 *                           Auto-generated by the upload system (A-07.2) when
 *                           the image is uploaded via MediaUploader; can also
 *                           be entered manually here.
 *
 *   Gallery Images (dynamic list, max GALLERY_MAX_IMAGES = 15):
 *     gallery[i].secureUrl — HTTPS image URL (required per existing item)
 *     gallery[i].altText   — accessibility alt text (optional, max 200 chars)
 *     gallery[i].blurDataUrl, publicId — preserved from existing items, not edited here
 *
 *   360° Video (optional):
 *     video360Url          — Cloudinary video URL (HTTPS, optional)
 *
 * IMAGE PREVIEW:
 *   Every URL input shows a live thumbnail:
 *     Empty URL      → grey box with image icon (placeholder)
 *     Non-HTTPS URL  → red X indicator (not fetched for security)
 *     Valid HTTPS URL → <img> element; failure tracked per URL string
 *     Failed to load → grey box with broken indicator
 *
 *   Broken URLs are tracked by URL string (not index) so drag-to-reorder
 *   does not reset or misattribute the broken state.
 *   Regular <img> is used (not Next.js Image) because:
 *     1. Image dimensions are unknown at render time
 *     2. Admin-only context — LCP optimisation is not required here
 *     3. Cloudinary and arbitrary HTTPS URLs cannot always be configured
 *        in next.config.ts remotePatterns upfront
 *
 * DRAG-AND-DROP REORDER:
 *   HTML5 DnD events on each gallery item card.
 *   draggingIndexRef (ref) — source index; read in onDrop without stale closures.
 *   draggingIndex (state)  — drives 35% opacity on the card being dragged.
 *   dragOverIndex (state)  — shows the accent insertion bar on the target card.
 *
 *   onDragLeave uses e.currentTarget.contains(e.relatedTarget as Node) to
 *   prevent the drag-over indicator from flickering when the cursor moves
 *   between child elements inside the target card.
 *
 *   On drop: insertion-based splice algorithm (same as GalleryUploader A-07.4).
 *   On dragend: clears all drag state as a safety net (fires even if the
 *   drop occurred outside a valid target).
 *
 * VALIDATION:
 *   Per-field blur validation using validators from A-08.6 additions:
 *     heroImageUrl:     validateHeroGalleryUrl (required + HTTPS)
 *     heroBlurDataUrl:  validateHttpsUrl (optional + HTTPS if provided)
 *     video360Url:      validateHttpsUrl (optional + HTTPS if provided)
 *     gallery[i].url:   validateGalleryItemUrl (required per item + HTTPS + dedup)
 *     gallery[i].altText: validateAltText (optional + max 200 chars)
 *
 *   Local blur errors stored in localErrors / localGalleryErrors state.
 *   Parent errors (BikeFormGalleryErrors from BikeFormShell) merged before
 *   render — local errors take precedence (they reflect the latest input).
 *
 * WHY 'use client':
 *   useState (localErrors, localGalleryErrors, draggingIndex, dragOverIndex,
 *             brokenUrls)
 *   useRef   (draggingIndexRef)
 *   useCallback (change, blur, DnD handlers, add/remove)
 *   DragEvent handlers (onDragStart, onDragEnter, onDragOver,
 *                       onDragLeave, onDrop, onDragEnd)
 */

