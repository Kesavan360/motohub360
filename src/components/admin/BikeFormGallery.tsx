export interface BikeFormGalleryProps {
  /*
   * values — the current Gallery section state from BikeFormShell.
   * Contains heroImageUrl, heroBlurDataUrl, gallery[], video360Url.
   */
  values: BikeFormGalleryValues

  /*
   * errors — section-level errors from BikeFormShell's last full validation.
   * Merged with local blur errors; local errors take precedence.
   */
  errors?: BikeFormGalleryErrors

  /*
   * onChange — fires on every field mutation with the updated values.
   * BikeFormShell wires this to updateGallery().
   */
  onChange: (values: BikeFormGalleryValues) => void

  /*
   * disabled — all inputs and buttons are inert when true (form is submitting).
   */
  disabled?: boolean

  brandSlug: string
  slug: string
}

